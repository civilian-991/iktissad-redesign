/** Map of all article type configurations, keyed by ArticleType enum value */
export const ARTICLE_TYPE_CONFIGS: Record<ArticleType, ArticleTypeConfig> = {
  [ArticleType.NEWS]: newsPreset,
  [ArticleType.REPORT]: reportPreset,
  [ArticleType.ANALYSIS]: analysisPreset,
  [ArticleType.INTERVIEW]: interviewPreset,
  [ArticleType.OPINION]: opinionPreset,
}

/**
 * Returns the full ArticleTypeConfig for the given article type.
 * Throws if an unknown type is passed (guards against enum drift).
 */
export function getStylePreset(articleType: ArticleType): ArticleTypeConfig {
  const config = ARTICLE_TYPE_CONFIGS[articleType]
  if (!config) {
    throw new Error(`[arabic-editorial] Unknown article type: "${articleType}"`)
  }
  return config
}
